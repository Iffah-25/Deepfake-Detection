
/**
 * Detection Service
 * Connects the existing React frontend to the trained
 * AFEM-Xception-v2 FastAPI backend.
 *
 * Supported input: images
 * Supported predictions: REAL / FAKE
 *
 * Important:
 * - Does not generate mock predictions.
 * - Does not silently fall back to simulated detection.
 * - Does not claim video, DCT, or temporal analysis.
 */

const API_BASE_URL = (
  import.meta.env.VITE_API_BASE_URL || ""
).replace(/\/+$/, "");

const SUPPORTED_IMAGE_TYPES = new Set([
  "image/jpeg",
  "image/png",
  "image/webp",
  "image/bmp",
]);

const MAX_FILE_SIZE = 10 * 1024 * 1024; // 10 MB

/**
 * Main detection function.
 *
 * @param {File} file Uploaded image
 * @param {Object} options Optional UI settings
 * @param {Function} onProgress Progress callback
 * @returns {Promise<Object>} Normalized detection result
 */
export const detectMedia = async (
  file,
  options = {},
  onProgress = () => {}
) => {
  if (!file) {
    throw new Error("Please select an image first.");
  }

  if (!API_BASE_URL) {
    throw new Error(
      "Detection API is not configured. Add VITE_API_BASE_URL to frontend/.env.local and restart the frontend."
    );
  }

  if (file.type.startsWith("video/")) {
    throw new Error(
      "Video detection is not supported yet. Please upload a JPG, PNG, WEBP, or BMP image."
    );
  }

  if (!SUPPORTED_IMAGE_TYPES.has(file.type)) {
    throw new Error(
      "Unsupported file type. Please upload a JPG, PNG, WEBP, or BMP image."
    );
  }

  if (file.size === 0) {
    throw new Error("The selected file is empty.");
  }

  if (file.size > MAX_FILE_SIZE) {
    throw new Error("The image must be 10 MB or smaller.");
  }

  onProgress(1, 3, "Validating image...");
  onProgress(2, 3, "Sending image to AFEM-Xception...");

  const result = await callRealBackendApi(file, options);

  onProgress(3, 3, "Analysis completed.");

  return result;
};

/**
 * Sends the uploaded image to FastAPI.
 */
const callRealBackendApi = async (file, options = {}) => {
  const formData = new FormData();
  formData.append("file", file);

  // Retained for compatibility with the existing frontend.
  // The current backend does not use analysis_type.
  if (options.analysisType) {
    formData.append("analysis_type", options.analysisType);
  }

  let response;

  try {
    response = await fetch(`${API_BASE_URL}/api/detect`, {
      method: "POST",
      body: formData,
    });
  } catch {
    throw new Error(
      "Could not connect to the detection backend. Ensure FastAPI is running at http://127.0.0.1:8000."
    );
  }

  if (!response.ok) {
    let message = `Detection failed with HTTP ${response.status}.`;

    try {
      const errorData = await response.json();

      if (errorData.detail) {
        message =
          typeof errorData.detail === "string"
            ? errorData.detail
            : JSON.stringify(errorData.detail);
      }
    } catch {
      // Keep the HTTP status message if the response is not JSON.
    }

    throw new Error(message);
  }

  let data;

  try {
    data = await response.json();
  } catch {
    throw new Error("The detection backend returned an invalid response.");
  }

  if (data.result !== "REAL" && data.result !== "FAKE") {
    throw new Error("The backend returned an unsupported prediction.");
  }

  if (
    typeof data.confidence !== "number" ||
    !Number.isFinite(data.confidence)
  ) {
    throw new Error("The backend returned an invalid confidence score.");
  }

  const realProbability = data.metrics?.realProbability;
  const fakeProbability = data.metrics?.fakeProbability;

  return {
    id: data.analysisId || `analysis-${Date.now()}`,

    result: data.result,
    confidence: data.confidence,

    fileName: file.name,
    fileSize: file.size,
    fileType: "image",
    mimeType: file.type,

    analyzedAt: new Date().toISOString(),

    processingTime: data.processingTime,
    modelVersion: data.modelVersion || "AFEM-Xception-v2",

    summary:
      data.message ||
      "Prediction generated by the trained AFEM-Xception model. " +
        "This result is not definitive proof of authenticity or manipulation.",

    metrics: {
      ...(data.metrics || {}),
      realProbability,
      fakeProbability,
    },

    // Explicitly avoid claiming unsupported forensic analyses.
    findings: [
      "Prediction generated by the trained AFEM-Xception-v2 model.",
      "AFEM frequency-domain preprocessing was applied.",
      "The prediction is not definitive proof of authenticity or manipulation.",
    ],
  };
};

